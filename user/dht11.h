#ifndef __DHT11_H
#define __DHT11_H

#include <stdbool.h>
#include <stdint.h>

/* ================================================================
 * DHT11 温湿度传感器驱动（单总线协议）
 *
 * 硬件接线：
 *   VCC  -> 3.3V
 *   GND  -> GND
 *   DATA -> GPIO 13 （需外加 4.7kΩ ~ 10kΩ 上拉到 3.3V）
 *
 * 协议时序：
 *   主机起始：拉低 ≥18ms 后拉高 20~40μs 释放总线
 *   DHT 响应：低 80μs → 高 80μs → 开始发送 40 位数据
 *   每位编码：低 50μs + 高 26~28μs（0） / 70μs（1）
 *
 * 数据格式（5 字节）：
 *   [湿度整数, 湿度小数, 温度整数, 温度小数, 校验和]
 *   DHT11 小数字段恒为 0，分辨率 1℃ / 1%RH
 *
 * 采样间隔：
 *   DHT11 最小 1 秒/次。本驱动内置 1 秒缓存，连续短时间内多次调用
 *   只触发一次实际读取，多个调用方共享同一次结果。
 * ================================================================ */

/**
 * @brief 一次性初始化
 *
 * 配置 GPIO 13 为开漏输入输出 + 内部上拉，创建模块互斥锁。
 * 建议在 app_main 单线程阶段调用一次。重复调用安全。
 */
void dht11_init(void);

/**
 * @brief 读取温度（仅整数℃）
 *
 * @param out_temp_c  输出温度（摄氏度），范围 0~50（DHT11 工作量程）
 * @return true 成功；false 通讯失败 / 校验错误 / 模块未 init
 *
 * 阻塞时长：~25ms（首次或缓存过期），<1ms（缓存命中）
 */
bool dht11_read_temp(int *out_temp_c);

/**
 * @brief 读取湿度（仅整数 %RH）
 *
 * @param out_humi_pct  输出相对湿度百分比，范围 20~90
 * @return true 成功；false 通讯失败 / 校验错误 / 模块未 init
 */
bool dht11_read_humi(int *out_humi_pct);

#endif
